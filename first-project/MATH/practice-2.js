/*
В переменных userName, userSurname даны имя и фамилия пользователя.
При этом в строках беспорядок с большими и маленькими буквами, и нужно оформить строки единообразно. 
Для этого первые буквы имени и фамилии приведите к верхнему регистру (большие буквы), 
а оставшиеся — к нижнему (маленькие буквы).
Запишите результат в новые переменные и выведите их значения с помощью console.log.
С помощью тернарных операторов и console.log выведите сообщение «Имя было преобразовано» 
или «Имя осталось без изменений» для имени и фамилии в зависимости от того, были ли исходные строки равны преобразованным.
*/

/*
Разбор задачи
Чтобы решить эту задачу, нам нужно выполнить четыре шага:
Вырезать первую букву и сделать её заглавной (toUpperCase()).
Вырезать остальные буквы и сделать их строчными (toLowerCase()).
Объединить эти части в новые переменные.
Сравнить старую строку с новой через тернарный оператор ? : и вывести лог.
*/

// Исходные данные (для проверки возьмем разный регистр)
let userName = "иВАН";
let userSurname = "пЕтРоВ";

// 1. Преобразуем имя
let correctedName = userName.substring(0, 1).toUpperCase() + userName.substring(1).toLowerCase();

// 2. Преобразуем фамилию
let correctedSurname = userSurname.substring(0, 1).toUpperCase() + userSurname.substring(1).toLowerCase();

// 3. Выводим результат преобразования
console.log("Результат:", correctedName, correctedSurname);

// 4. Проверяем изменения с помощью тернарного оператора
console.log(userName === correctedName ? "Имя осталось без изменений" : "Имя было преобразовано");
console.log(userSurname === correctedSurname ? "Фамилия осталась без изменений" : "Фамилия была преобразована");


